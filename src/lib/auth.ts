import crypto from "node:crypto";
import type { IncomingMessage, ServerResponse } from "node:http";

export const SESSION_COOKIE_NAME = "empower_admin_session";
export const SESSION_TTL_SECONDS = 60 * 60 * 24; // 24 hours

function getSessionSecret(): string {
  const secret = process.env.SESSION_SECRET?.trim();
  if (secret) return secret;

  if (process.env.NODE_ENV === "production") {
    throw new Error("SESSION_SECRET environment variable is required in production.");
  }
  return "dev-insecure-session-secret-change-me";
}

function getAdminPasswordHash(): string | null {
  const hash = process.env.ADMIN_PASSWORD_HASH?.trim();
  return hash || null;
}

/**
 * Verifies a plaintext password against ADMIN_PASSWORD_HASH.
 * Supports:
 *   - `scrypt:<saltHex>:<derivedHex>` (generated by `npm run hash-password`)
 *   - `sha256:<hex>`
 *   - raw 64-char hex sha256
 */
export function verifyAdminPassword(password: string): boolean {
  const configured = getAdminPasswordHash();
  if (!configured || !password) return false;

  if (configured.startsWith("scrypt:")) {
    const parts = configured.split(":");
    if (parts.length !== 3) return false;
    const [, salt, expectedHex] = parts;
    if (!salt || !expectedHex) return false;
    try {
      const derived = crypto.scryptSync(password, salt, 64);
      const expected = Buffer.from(expectedHex, "hex");
      if (derived.length !== expected.length) return false;
      return crypto.timingSafeEqual(derived, expected);
    } catch {
      return false;
    }
  }

  const normalizedHex = configured.startsWith("sha256:")
    ? configured.slice("sha256:".length)
    : configured;

  if (!/^[a-f0-9]{64}$/i.test(normalizedHex)) {
    return false;
  }

  const candidate = crypto.createHash("sha256").update(password).digest();
  const expected = Buffer.from(normalizedHex, "hex");
  return crypto.timingSafeEqual(candidate, expected);
}

export function generateSessionId(): string {
  return crypto.randomBytes(32).toString("hex");
}

export function signSessionId(sessionId: string): string {
  const hmac = crypto
    .createHmac("sha256", getSessionSecret())
    .update(sessionId)
    .digest("hex");
  return `${sessionId}.${hmac}`;
}

export function verifySignedSessionToken(token: string): string | null {
  const dotIdx = token.lastIndexOf(".");
  if (dotIdx <= 0) return null;

  const sessionId = token.slice(0, dotIdx);
  const signature = token.slice(dotIdx + 1);
  if (!sessionId || !signature) return null;

  const expectedSig = crypto
    .createHmac("sha256", getSessionSecret())
    .update(sessionId)
    .digest("hex");

  const sigBuf = Buffer.from(signature, "utf8");
  const expectedBuf = Buffer.from(expectedSig, "utf8");
  if (sigBuf.length !== expectedBuf.length) return null;

  return crypto.timingSafeEqual(sigBuf, expectedBuf) ? sessionId : null;
}

export function parseCookies(cookieHeader: string | undefined): Record<string, string> {
  const result: Record<string, string> = {};
  if (!cookieHeader) return result;

  for (const part of cookieHeader.split(";")) {
    const idx = part.indexOf("=");
    if (idx <= 0) continue;
    const key = part.slice(0, idx).trim();
    const value = decodeURIComponent(part.slice(idx + 1).trim());
    if (key) result[key] = value;
  }
  return result;
}

export function extractSessionIdFromRequest(req: IncomingMessage): string | null {
  const cookies = parseCookies(req.headers.cookie);
  const token = cookies[SESSION_COOKIE_NAME];
  if (!token) return null;
  return verifySignedSessionToken(token);
}

export function buildSessionCookie(signedToken: string): string {
  const isProd = process.env.NODE_ENV === "production";
  const parts = [
    `${SESSION_COOKIE_NAME}=${encodeURIComponent(signedToken)}`,
    "HttpOnly",
    "Path=/",
    "SameSite=Lax",
    `Max-Age=${SESSION_TTL_SECONDS}`,
  ];
  if (isProd) {
    parts.push("Secure");
  }
  return parts.join("; ");
}

export function buildClearSessionCookie(): string {
  const isProd = process.env.NODE_ENV === "production";
  const parts = [
    `${SESSION_COOKIE_NAME}=`,
    "HttpOnly",
    "Path=/",
    "SameSite=Lax",
    "Max-Age=0",
  ];
  if (isProd) {
    parts.push("Secure");
  }
  return parts.join("; ");
}

export function setCookieHeader(res: ServerResponse, cookieValue: string): void {
  res.setHeader("Set-Cookie", cookieValue);
}

export function getClientIp(req: IncomingMessage): string {
  const forwarded = req.headers["x-forwarded-for"];
  if (typeof forwarded === "string" && forwarded.trim()) {
    return forwarded.split(",")[0].trim();
  }
  if (Array.isArray(forwarded) && forwarded.length > 0) {
    return forwarded[0].trim();
  }
  return req.socket?.remoteAddress ?? "unknown";
}
